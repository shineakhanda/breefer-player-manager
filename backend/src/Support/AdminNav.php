<?php

namespace Breefer\PlayerManager\Support;

use Illuminate\Support\Facades\Log;

/**
 * Publishes a tiny Filament page stub into app/Filament/Pages so the settings page
 * appears in the admin sidebar under "Breefer". The stub mentions
 * "extensions/breefer-player-manager/", which is how Reviactyl removes it when the extension is deleted.
 * Filament discovers admin pages before extension boot hooks run, so the stub registers
 * this extension's autoloader itself; the page hides itself while the extension is disabled.
 */
final class AdminNav
{
    public const ICON = 'tabler-users';

    public static function className(): string
    {
        $base = preg_replace('/^Breefer\s+/', '', Plugin::NAME) ?? Plugin::NAME;

        return 'Breefer'.str_replace(' ', '', ucwords(preg_replace('/[^A-Za-z0-9 ]/', ' ', $base) ?? $base));
    }

    public static function slug(): string
    {
        return 'breefer/'.preg_replace('/^breefer-/', '', Plugin::ID);
    }

    public static function stub(): string
    {
        $class = self::className();
        $parent = '\\Breefer\PlayerManager\\Support\\FilamentSettingsPage';
        $slug = self::slug();
        $icon = self::ICON;
        $name = Plugin::NAME;
        $id = Plugin::ID;
        $src = var_export(Plugin::path('backend/src'), true);
        $prefix = var_export('Breefer\PlayerManager'.'\\', true);
        // Filament discovers pages before extension boot hooks run: register the autoloader here too.
        $loader = <<<'LOADER'
(static function (): void {
    $src = __SRC__;
    $prefix = __PREFIX__;
    if (! is_dir($src)) {
        return;
    }
    spl_autoload_register(static function (string $class) use ($src, $prefix): void {
        if (strncmp($class, $prefix, strlen($prefix)) !== 0) {
            return;
        }
        $file = $src.'/'.str_replace('\\', '/', substr($class, strlen($prefix))).'.php';
        if (is_file($file)) {
            require_once $file;
        }
    });
})();
LOADER;
        $loader = str_replace(['__SRC__', '__PREFIX__'], [$src, $prefix], $loader);

        return <<<PHP
<?php

/*
 * Auto-generated by {$name} (extensions/{$id}/).
 * Reviactyl deletes this file when the extension is removed. Do not edit.
 */

namespace App\\Filament\\Pages;

{$loader}

if (class_exists({$parent}::class)) {
    class {$class} extends {$parent}
    {
        public static function getSlug(?\\Filament\\Panel \$panel = null): string
        {
            return '{$slug}';
        }

        public static function getNavigationIcon(): ?string
        {
            return '{$icon}';
        }
    }
}

PHP;
    }

    public static function install(): void
    {
        try {
            $dir = app_path('Filament/Pages');
            if (! is_dir($dir)) {
                return;
            }
            $target = $dir.DIRECTORY_SEPARATOR.self::className().'.php';
            $stub = self::stub();
            if (is_file($target) && @file_get_contents($target) === $stub) {
                return;
            }
            if (! is_writable($dir) && ! (is_file($target) && is_writable($target))) {
                return; // settings stay reachable at /admin/extensions/breefer-player-manager
            }
            file_put_contents($target, $stub);
            // A cached Filament component list would hide the new page until the next optimize.
            foreach (glob(base_path('bootstrap/cache/filament/panels/*.php')) ?: [] as $cache) {
                @unlink($cache);
            }
        } catch (\Throwable $exception) {
            Log::warning('[Breefer] Could not publish admin page.', ['extension' => Plugin::ID, 'error' => $exception->getMessage()]);
        }
    }
}
